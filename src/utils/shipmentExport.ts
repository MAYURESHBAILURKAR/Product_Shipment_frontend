import * as Linking from "expo-linking";
import * as Print from "expo-print";
import * as Sharing from "expo-sharing";

export interface StatementRow {
  date: string;
  ref: string;
  user: string;
  status: string;
  items: number;
  amount: number;
}

export interface EarningsMonthRow {
  label: string; // e.g. "Aug 2026"
  key: string; // "2026-08" for sorting
  shipments: number;
  units: number;
  amount: number;
}

