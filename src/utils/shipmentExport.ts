// Printable shipment-log statement (used by Shipment Logs export).
export function buildStatementHtml(opts: {
  rows: StatementRow[];
  periodLabel: string;
  showUser: boolean;
  ownerName?: string;
}) {
  const { rows, periodLabel, showUser, ownerName } = opts;
  const totalItems = rows.reduce((a, r) => a + r.items, 0);
  const totalAmount = rows.reduce((a, r) => a + r.amount, 0);

  const head = `<tr>
    <th>Date</th><th>Shipment</th>${showUser ? "<th>User</th>" : ""}
    <th>Status</th><th class="num">Items</th><th class="num">Value</th>
  </tr>`;

  const body = rows
    .map(
      (r) => `<tr>
      <td>${r.date}</td>
      <td>${r.ref}</td>
      ${showUser ? `<td>${r.user}</td>` : ""}
      <td><span class="badge" style="background:${statusColor(r.status.toLowerCase())}">${r.status}</span></td>
      <td class="num">${r.items}</td>
      <td class="num">${money(r.amount)}</td>
    </tr>`,
    )
    .join("");

  const html = `<table><thead>${head}</thead><tbody>${body}</tbody></table>
  <div class="totals"><div class="totals-inner">
    <div><span>Shipments</span><span>${rows.length}</span></div>
    <div><span>Total items</span><span>${totalItems}</span></div>
    <div class="grand"><span>Total value</span><span>${money(totalAmount)}</span></div>
  </div></div>`;

  return docShell(
    "Shipment Statement",
    periodLabel,
    `${ownerName ? `For: ${ownerName} · ` : ""}${rows.length} shipments`,
    html,
  );
}

// Printable earnings summary (used by My Earnings export).
export function buildEarningsHtml(opts: {
  months: EarningsMonthRow[];
  ratePerUnit: number;
  ownerName?: string;
}) {
  const { months, ratePerUnit, ownerName } = opts;
  const totalShipments = months.reduce((a, m) => a + m.shipments, 0);
  const totalUnits = months.reduce((a, m) => a + m.units, 0);
  const totalAmount = months.reduce((a, m) => a + m.amount, 0);

  const head = `<tr><th>Month</th><th class="num">Shipments</th><th class="num">Units</th><th class="num">Earnings</th></tr>`;
  const body = months
    .map(
      (m) => `<tr>
      <td>${m.label}</td>
      <td class="num">${m.shipments}</td>
      <td class="num">${m.units}</td>
      <td class="num">${money(m.amount)}</td>
    </tr>`,
    )
    .join("");

  const html = `<table><thead>${head}</thead><tbody>${body}</tbody></table>
  <div class="totals"><div class="totals-inner">
    <div><span>Payout rate</span><span>${money(ratePerUnit)} / unit</span></div>
    <div><span>Shipments</span><span>${totalShipments}</span></div>
    <div><span>Total units</span><span>${totalUnits}</span></div>
    <div class="grand"><span>Total earnings</span><span>${money(totalAmount)}</span></div>
  </div></div>`;

  return docShell(
    "Earnings Statement",
    "Monthly payout summary",
    `${ownerName ? `For: ${ownerName} · ` : ""}${months.length} months covered`,
    html,
  );
}

const csvEscape = (v: string | number) => {
  const s = String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function statementToCsv(rows: StatementRow[], showUser: boolean): string {
  const header = ["Date", "Shipment", ...(showUser ? ["User"] : []), "Status", "Items", "Value"];
  const lines = rows.map((r) =>
    [
      r.date,
      r.ref,
      ...(showUser ? [r.user] : []),
      r.status,
      r.items,
      r.amount,
    ]
      .map(csvEscape)
      .join(","),
  );
  return [header.join(","), ...lines].join("\n");
}

export function earningsToCsv(months: EarningsMonthRow[]): string {
  const header = "Month,Shipments,Units,Earnings";
  const lines = months.map((m) =>
    [m.label, m.shipments, m.units, m.amount].map(csvEscape).join(","),
  );
  return [header, ...lines].join("\n");
}

// Generates the PDF in cache and opens the native share sheet.
// Returns false when generation/sharing is unavailable (e.g. web).
export async function sharePdf(
  html: string,
  dialogTitle = "Share statement",
): Promise<boolean> {
  try {
    const { uri } = await Print.printToFileAsync({ html });
    if (!(await Sharing.isAvailableAsync())) return false;
    await Sharing.shareAsync(uri, {
      mimeType: "application/pdf",
      UTI: "com.adobe.pdf",
      dialogTitle,
    });
    return true;
  } catch (error) {
    console.error("sharePdf failed:", error);
    return false;
  }
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await Clipboard.setStringAsync(text);
    return true;
  } catch (error) {
    console.error("copyText failed:", error);
    return false;
  }
}

// Opens WhatsApp with the text pre-filled. Prefers the native app scheme;
// falls back to wa.me (browser WhatsApp) when the app isn't installed.
// Returns false when neither can be opened (e.g. web).
export async function shareTextToWhatsApp(text: string): Promise<boolean> {
  const encoded = encodeURIComponent(text);
  try {
    const appUrl = `whatsapp://send?text=${encoded}`;
    const canOpenApp = await Linking.canOpenURL(appUrl);
    if (canOpenApp) {
      await Linking.openURL(appUrl);
      return true;
    }
    // No WhatsApp app — use the universal wa.me link.
    await Linking.openURL(`https://wa.me/?text=${encoded}`);
    return true;
  } catch (error) {
    console.error("shareTextToWhatsApp failed:", error);
    return false;
  }
}
